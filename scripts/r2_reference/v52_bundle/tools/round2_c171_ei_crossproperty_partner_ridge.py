"""C171: leakage-safe Ei partner reconstruction with low-dimensional Ridge.

This is a clean official-only experiment.  It predicts a missing Eea or Egc
partner from official structure features plus the other observed properties,
but explicitly excludes Ei from every partner model.  The Ei identity is used
only when its partner values are available at the same canonical structure.
Blend weights are estimated inside the Ei outer folds and are not selected
from any test-external_label material.
"""
from pathlib import Path
import json
import pickle
import time

import numpy as np
import pandas as pd
from sklearn.linear_model import Ridge
from sklearn.metrics import r2_score
from sklearn.model_selection import KFold
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import StandardScaler


ROOT = Path("/home/vishwa/Desktop/AISEHack-2.0/Polymer Prediction Challenge Round 2")
BASE = ROOT / "ppp-round-2"
SCR = Path(
    "/tmp/claude-1001/-home-vishwa-Desktop-AISEHack-2-0/"
    "b00b2b9e-6110-479c-9f4b-9e173328b74e/scratchpad"
)
OUT = ROOT / "experiments/CLEAN_OFFICIAL_ONLY"
TARGETS = ["tg", "egc", "egb", "ei", "eea", "nc", "eps"]
TI = {name: i for i, name in enumerate(TARGETS)}
SEED = 20260804


def r2(y, p):
    return float(r2_score(np.asarray(y, float), np.asarray(p, float)))


def load_state():
    features = pickle.loads((SCR / "features.pkl").read_bytes())
    idx = features["idx"]
    canon_map = features["canon_map"]
    n = len(features["canon_list"])
    train = pd.read_csv(BASE / "train.csv")
    archive = pd.read_csv(BASE / "archive/train.csv")

    labels = np.full((n, len(TARGETS)), np.nan, dtype=float)
    for j, target in enumerate(TARGETS):
        for frame in (archive, train):
            keyed = frame[frame.target_type.eq(target)].copy()
            keyed["canon"] = keyed["smiles"].map(canon_map)
            vals = keyed.groupby("canon")["target"].mean()
            for canon, value in vals.items():
                if canon in idx:
                    labels[idx[canon], j] = float(value)

    # These arrays were generated by the clean official-only loop from the
    # official structures.  P1 is structure-only; PFINAL is the established
    # corrected parent used by the C143/C162 clean comparisons.
    p1 = np.load(SCR / "out_clean_corrected/P1.npy")
    pfinal = np.load(SCR / "out_clean_corrected/PFINAL.npy")
    if p1.shape != labels.shape or pfinal.shape != labels.shape:
        raise RuntimeError((p1.shape, pfinal.shape, labels.shape))
    return features, labels, p1, pfinal


def compact_structure_features(features):
    blocks = features["blocks"]
    x = np.hstack([blocks["desc"], blocks["extra"], blocks["ipc"]]).astype(float)
    x[~np.isfinite(x)] = np.nan
    med = np.nanmedian(x, axis=0)
    med[~np.isfinite(med)] = 0.0
    bad = ~np.isfinite(x)
    x[bad] = np.take(med, np.where(bad)[1])
    return np.clip(x, -1e6, 1e6)


def partner_prediction(target, features, labels, p1):
    """Fit a partner model without using either the partner target or Ei."""
    j = TI[target]
    other = [k for k in range(len(TARGETS)) if k not in (j, TI["ei"])]
    observed = np.isfinite(labels)
    bank = np.where(observed, labels, p1)
    x = np.hstack([
        compact_structure_features(features),
        bank[:, other],
        observed[:, other].astype(float),
    ])
    fit_rows = np.where(observed[:, j])[0]
    alpha = 10.0 if target == "eea" else 100.0
    model = make_pipeline(StandardScaler(), Ridge(alpha=alpha))
    model.fit(x[fit_rows], labels[fit_rows, j])
    return model.predict(x)


def main():
    started = time.time()
    features, labels, p1, pfinal = load_state()
    observed = np.isfinite(labels)
    ei_rows = np.where(observed[:, TI["ei"]])[0]
    y = labels[ei_rows, TI["ei"]]

    # The parent is the corrected C143 Ei carrier: direct identity is used
    # only on rows with both official partners; all other rows keep PFINAL.
    parent = pfinal[ei_rows, TI["ei"]].copy()
    both = observed[ei_rows, TI["eea"]] & observed[ei_rows, TI["egc"]]
    identity = labels[ei_rows, TI["eea"]] + labels[ei_rows, TI["egc"]]
    parent[both] = 0.5 * parent[both] + 0.5 * identity[both]

    # Models are fitted on the full partner pools because evaluation rows are
    # exactly those rows where that partner is absent.  Ei is excluded from
    # partner features, so the current row's Ei label cannot enter.
    egc_hat_all = partner_prediction("egc", features, labels, p1)
    eea_hat_all = partner_prediction("eea", features, labels, p1)
    eea_present = observed[ei_rows, TI["eea"]]
    egc_present = observed[ei_rows, TI["egc"]]
    egc_missing = eea_present & ~egc_present
    eea_missing = ~eea_present & egc_present

    raw_from_egc = labels[ei_rows, TI["eea"]] + egc_hat_all[ei_rows]
    raw_from_eea = labels[ei_rows, TI["egc"]] + eea_hat_all[ei_rows]

    # Nested outer-fold estimation of the two blend coefficients.  The
    # partner predictions are fixed official-only cross-property predictions;
    # each coefficient is fitted only on the corresponding Ei training slice.
    folds = KFold(5, shuffle=True, random_state=SEED)
    nested = np.zeros(len(ei_rows), dtype=float)
    fold_records = []
    for train_pos, valid_pos in folds.split(ei_rows):
        pred = parent[valid_pos].copy()
        weights = {}
        for name, mode, raw in (
            ("missing_egc", egc_missing, raw_from_egc),
            ("missing_eea", eea_missing, raw_from_eea),
        ):
            fit_pos = np.intersect1d(train_pos, np.where(mode)[0])
            valid_mode_pos = np.intersect1d(valid_pos, np.where(mode)[0])
            if len(fit_pos) < 8 or len(valid_mode_pos) == 0:
                weights[name] = 0.0
                continue
            delta = raw[fit_pos] - parent[fit_pos]
            target_delta = y[fit_pos] - parent[fit_pos]
            weight = float(np.dot(delta, target_delta) / max(np.dot(delta, delta), 1e-12))
            weight = float(np.clip(weight, 0.0, 1.0))
            pred[np.isin(valid_pos, valid_mode_pos)] += weight * (
                raw[valid_mode_pos] - parent[valid_mode_pos]
            )
            weights[name] = weight
        nested[valid_pos] = pred
        fold_records.append({
            "train_rows": int(len(train_pos)),
            "valid_rows": int(len(valid_pos)),
            "weights": weights,
        })

    metrics = {
        "ei": {
            "n": int(len(ei_rows)),
            "parent_r2": r2(y, parent),
            "candidate_r2": r2(y, nested),
            "delta_r2": r2(y, nested) - r2(y, parent),
        }
    }
    # Preserve the corrected C143 clean comparison for the unchanged targets;
    # this is the composite score before the C162 EPS/Nc component bank.
    c143 = {
        "tg": 0.9153573687299403,
        "egc": 0.9249057744047514,
        "egb": 0.9541078896040173,
        "eea": 0.9295377162544358,
        "nc": 0.9205304844029711,
        "eps": 0.877040481326824,
    }
    parent_mean = float(np.mean(list(c143.values()) + [metrics["ei"]["parent_r2"]]))
    candidate_mean = float(np.mean(list(c143.values()) + [metrics["ei"]["candidate_r2"]]))
    metrics["composite"] = {
        "parent_mean_r2": parent_mean,
        "candidate_mean_r2": candidate_mean,
        "delta_mean_r2": candidate_mean - parent_mean,
        "c162_eps_nc_banked_mean_r2": candidate_mean + (
            (0.8927568748456813 - 0.877040481326824)
            + (0.9248926000000000 - 0.9205304844029711)
        ) / 7.0,
    }
    report = {
        "schema_version": "ppp.round2.clean-oof.v1",
        "experiment": "R2-C171-ei-crossproperty-partner-ridge",
        "official_only_fitting": True,
        "local_eval_read": False,
        "pretrained_weights": False,
        "same_row_ei_label_as_feature": False,
        "mechanism": "low-dimensional official-label partner Ridge; Ei excluded from partner features; nested availability-specific identity shrinkage",
        "partner_models": {
            "eea": {"alpha": 10.0, "fit_rows": int(np.sum(observed[:, TI["eea"]]))},
            "egc": {"alpha": 100.0, "fit_rows": int(np.sum(observed[:, TI["egc"]]))},
        },
        "availability": {
            "ei_rows": int(len(ei_rows)),
            "both_partners": int(np.sum(both)),
            "missing_egc": int(np.sum(egc_missing)),
            "missing_eea": int(np.sum(eea_missing)),
            "missing_both": int(np.sum(~eea_present & ~egc_present)),
        },
        "folds": fold_records,
        "metrics": metrics,
        "gate": {
            "ei_gain_at_least_0.010": bool(metrics["ei"]["delta_r2"] >= 0.010),
            "positive_nested_route": bool(metrics["ei"]["delta_r2"] > 0),
            "passed": bool(metrics["ei"]["delta_r2"] >= 0.010),
        },
        "elapsed_seconds": time.time() - started,
    }
    OUT.mkdir(parents=True, exist_ok=True)
    path = OUT / "R2-C171-ei-crossproperty-partner-ridge-clean-oof.json"
    path.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    print(json.dumps(report, indent=2), flush=True)


if __name__ == "__main__":
    main()
